/// A proof generated by the Noir/Barretenberg backend.
#[derive(Ord, PartialOrd, Eq, PartialEq)]
pub struct NoirProof {
    /// Raw proof bytes (without public inputs).
    pub proof: Vec<u8>,
    /// Public input field elements as byte vectors.
    pub public_inputs: Vec<Vec<u8>>,
}

impl Debug for NoirProof {
    fn fmt(&self, f: &mut Formatter<'_>) -> std::fmt::Result {
        f.write_str(&format!(
            "NoirProof{{ proof: {}, public_inputs: {}, proof_bytes: {:0X?} }}",
            self.proof.len(),
            self.public_inputs.len(),
            self.proof
        ))
    }
}

impl Proof for NoirProof {
    fn proof(&self) -> String {
        bs58::encode(&self.proof).into_string()
    }

    fn public_inputs(&self) -> Vec<String> {
        let mut public_inputs = Vec::new();
        for input in &self.public_inputs {
            public_inputs.push(bs58::encode(input).into_string());
        }

        public_inputs
    }
}

/// Splits a proof containing a 4-byte public input count prefix into public inputs and proof bytes.
///
/// The proof format used by zkpassport/noir_rs is:
/// ```text
/// [num_public_inputs (4 bytes BE)] [public_input_0: 32B] [public_input_1: 32B] ... [proof_bytes...]
/// ```
///
/// # Arguments
/// * `proof` - The combined proof with count prefix
///
/// # Returns
/// A tuple of (public_inputs, proof_bytes) where:
/// * `public_inputs` - Vector of public input byte vectors (each 32 bytes)
/// * `proof_bytes` - The remaining proof bytes after removing count and inputs
///
/// # Errors
/// Returns an error if the proof is malformed (too short or incomplete public inputs).
pub fn split_proof(proof: &[u8]) -> Result<(Vec<Vec<u8>>, Vec<u8>), String> {
    if proof.len() < 4 {
        return Err("proof too short: missing public input count prefix".to_string());
    }

    let num_public_inputs = u32::from_be_bytes([proof[0], proof[1], proof[2], proof[3]]) as usize;
    let bytes_per_input = 32;
    let public_inputs_size = num_public_inputs * bytes_per_input;

    if proof.len() < 4 + public_inputs_size {
        return Err(format!(
            "invalid proof format: expected {} public input bytes, but only {} bytes available after count prefix",
            public_inputs_size,
            proof.len() - 4
        ));
    }

    let public_inputs_bytes = &proof[4..4 + public_inputs_size];
    let proof_bytes = &proof[4 + public_inputs_size..];

    let public_inputs = (0..num_public_inputs)
        .map(|i| public_inputs_bytes[i * 32..(i + 1) * 32].to_vec())
        .collect();

    Ok((public_inputs, proof_bytes.to_vec()))
}

/// Recombines public inputs and proof bytes into a single proof with 4-byte count prefix.
///
/// This is the inverse of `split_proof()` and is used for proof verification.
///
/// # Arguments
/// * `proof` - The raw proof bytes (without public inputs)
/// * `public_inputs` - The public input byte vectors (each 32 bytes)
///
/// # Returns
/// A combined proof with the format: [count: 4B BE][inputs...][proof...]
fn combine_proof(proof: Vec<u8>, public_inputs: Vec<Vec<u8>>) -> Vec<u8> {
    let num_public_inputs = public_inputs.len() as u32;
    let mut combined = Vec::new();
    combined.extend_from_slice(&num_public_inputs.to_be_bytes());

    for input in public_inputs {
        combined.extend_from_slice(&input);
    }

    combined.extend_from_slice(&proof);
    combined
}

impl NoirProof {
    fn to_noir_proof(&self) -> Vec<u8> {
        combine_proof(self.proof.clone(), self.public_inputs.clone())
    }

    /// Public accessor for the combined Honk proof bytes
    /// (`[num_inputs:4B BE][public_inputs:32B*K][proof]`). This is the
    /// exact byte layout consumed by the on-chain `zk_verify`
    /// precompile and emitted to wallets as the `aggregationProof`
    /// calldata.
    pub fn to_combined(&self) -> Vec<u8> {
        self.to_noir_proof()
    }
}

/// Noir circuit for full proofs (ownership + Merkle inclusion).
pub struct NoirFullProofCircuit {
    config: NoirCircuitConfig,
    _srs: u32,
    verification_key: Vec<u8>,
}

impl ZKCircuit<NoirCircuitConfig, NoirProof> for NoirFullProofCircuit {
    type Witness = FullProofWitness;

    fn setup(c: NoirCircuitConfig) -> anyhow::Result<Self> {
        let bytecode = &c.circuit.bytecode;
        let srs = setup_srs_from_bytecode(bytecode, None, false).map_err(Error::msg)?;
        let vk = match c.scheme {
            ZKMode::UltraHonk => get_ultra_honk_verification_key(bytecode, c.low_memory, None),
            ZKMode::UltraHonkKeccak => {
                get_ultra_honk_keccak_verification_key(bytecode, false, c.low_memory, None)
            }
        }
        .map_err(Error::msg)?;

        Ok(NoirFullProofCircuit {
            config: c,
            _srs: srs,
            verification_key: vk,
        })
    }

    fn version(&self) -> ZKCircuitVersion {
        ZKCircuitVersion {
            circuit_hash: self.config.circuit.hash.to_string(),
            circuit_version: self.config.version.to_string(),
            circuit_type: "noir".to_string(),
        }
    }

    fn prove(&self, witness: FullProofWitness) -> anyhow::Result<NoirProof> {
        let circuit = &self.config.circuit;
        let bytecode = &circuit.bytecode;
        let witness_map = NoirFullProofCircuit::create_witness_map(&witness).map_err(Error::msg)?;
        let proof = match self.config.scheme {
            ZKMode::UltraHonk => prove_ultra_honk(
                bytecode,
                witness_map,
                self.verification_key.clone(),
                self.config.low_memory,
                None,
            ),
            ZKMode::UltraHonkKeccak => prove_ultra_honk_keccak(
                bytecode,
                witness_map,
                self.verification_key.clone(),
                false,
                self.config.low_memory,
                None,
            ),
        }
        .map_err(|error| Error::msg(error.to_string()))?;

        let (public_inputs, proof_bytes) = split_proof(&proof).map_err(Error::msg)?;

        Ok(NoirProof {
            proof: proof_bytes,
            public_inputs,
        })
    }

    fn verify(&self, proof: NoirProof) -> Result<bool, Error> {
        let combined_proof = proof.to_noir_proof();

        match self.config.scheme {
            ZKMode::UltraHonk => verify_ultra_honk(combined_proof, self.verification_key.clone()),
            ZKMode::UltraHonkKeccak => {
                verify_ultra_honk_keccak(combined_proof, self.verification_key.clone(), false)
            }
        }
        .map_err(Error::msg)
    }
}

// Max depth of SMT, one block may contain 2^8 tributes
// so network can handle about 1M tributes per second
pub use outbe_crypto_common::merkle::SPARSE_MERKLE_PATH_DEPTH;

impl NoirFullProofCircuit {
    fn create_witness_map(witness: &FullProofWitness) -> Result<WitnessMap<FieldElement>, Error> {
        // Circuit main() signature (must match exactly):
        //     pk: EmbeddedCurvePoint,
        //     signature: [u8; 64],
        //     nonce: Field,
        //     merkle_path_siblings: [Field; 8],
        //     merkle_path_indices: [u8; 8],
        //     owner: pub Field,
        //     nft_hash: pub Field,
        //     expected_merkle_root: pub Field,

        use outbe_crypto_common::merkle::MerklePathElementIndex;

        let mut witness_vec = Vec::new();

        // pk.x as Field (Grumpkin coord, BE-decoded from 32 bytes)
        witness_vec.push(FieldElement::from_be_bytes_reduce(
            &witness.private_inputs.ownership.public_key_x,
        ));
        // pk.y as Field
        witness_vec.push(FieldElement::from_be_bytes_reduce(
            &witness.private_inputs.ownership.public_key_y,
        ));

        // signature as [u8; 64] -- Schnorr/Grumpkin (s || e)
        let signature = witness
            .public_inputs
            .ownership
            .signature
            .iter()
            .map(|byte| FieldElement::from(*byte as u32));
        witness_vec.extend(signature);

        // nonce as Field
        witness_vec.push(FieldElement::from_be_bytes_reduce(
            &witness.private_inputs.ownership.nonce,
        ));

        // merkle_path_siblings as [Field; 8] and merkle_path_indices as [u8; 8]
        {
            let diff = SPARSE_MERKLE_PATH_DEPTH - witness.private_inputs.merkle_path.len();

            // Siblings as Field values
            let mut merkle_path_siblings: Vec<FieldElement> = witness
                .private_inputs
                .merkle_path
                .iter()
                .map(|item| FieldElement::from_be_bytes_reduce(&item.node_hash))
                .collect();
            merkle_path_siblings.extend(vec![FieldElement::zero(); diff]);
            witness_vec.extend(merkle_path_siblings);

            // Indices mapped to Noir convention: Right->1 (current is left), Left->0 (sibling is left)
            let mut merkle_path_indices: Vec<FieldElement> = witness
                .private_inputs
                .merkle_path
                .iter()
                .map(|item| match item.index {
                    MerklePathElementIndex::Right => FieldElement::from(1u32),
                    MerklePathElementIndex::Left => FieldElement::zero(),
                    MerklePathElementIndex::Skip => FieldElement::zero(),
                })
                .collect();
            merkle_path_indices.extend(vec![FieldElement::zero(); diff]);
            witness_vec.extend(merkle_path_indices);
        }

        // expected_ownership as pub Field
        witness_vec.push(FieldElement::from_be_bytes_reduce(
            &witness.public_inputs.ownership.ownership,
        ));

        // nft_hash as pub Field — lives inside ownership now.
        witness_vec.push(FieldElement::from_be_bytes_reduce(
            &witness.public_inputs.ownership.nft_hash,
        ));

        // expected_merkle_root as pub Field
        witness_vec.push(FieldElement::from_be_bytes_reduce(
            &witness.public_inputs.merkle_root,
        ));

        from_vec_to_witness_map(witness_vec).map_err(Error::msg)
    }
}

