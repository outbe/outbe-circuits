impl NoirOwnershipCircuit {
    /// Create a witness map for the Schnorr/Grumpkin ownership-only
    /// circuit.
    ///
    /// Circuit `main()` parameter order (must match
    /// `outbe-ownership-circuit/src/main.nr`):
    ///
    /// ```text
    /// pk          : EmbeddedCurvePoint    // private — 2 Fields (pk.x, pk.y)
    /// signature   : [u8; 64]              // private — 64 bytes (Schnorr s||e)
    /// nonce       : Field                 // private
    /// owner       : pub Field
    /// nft_hash    : pub Field
    /// ```
    ///
    /// `public_key_x` / `public_key_y` in `OwnershipPrivateInputs` are
    /// 32-byte LE encodings of Grumpkin Fr coordinates (was: SEC1
    /// bytes for secp256k1).
    fn create_ownership_witness_map(
        witness: &OwnershipWitness,
    ) -> Result<WitnessMap<FieldElement>, Error> {
        let mut witness_vec = Vec::new();

        // pk.x as one Field (Grumpkin coord, BE-decoded from 32 bytes)
        witness_vec.push(FieldElement::from_be_bytes_reduce(
            &witness.private_inputs.public_key_x,
        ));
        // pk.y as one Field
        witness_vec.push(FieldElement::from_be_bytes_reduce(
            &witness.private_inputs.public_key_y,
        ));
        // signature as [u8; 64] — Schnorr/Grumpkin (s || e). The
        // `noir-lang/schnorr` crate expects this layout exactly.
        for &byte in witness.public_inputs.signature.iter() {
            witness_vec.push(FieldElement::from(byte as u32));
        }
        // nonce as Field
        witness_vec.push(FieldElement::from_be_bytes_reduce(
            &witness.private_inputs.nonce,
        ));

        // owner as pub Field
        witness_vec.push(FieldElement::from_be_bytes_reduce(
            &witness.public_inputs.ownership,
        ));
        // nft_hash as pub Field
        witness_vec.push(FieldElement::from_be_bytes_reduce(
            &witness.public_inputs.nft_hash,
        ));

        from_vec_to_witness_map(witness_vec).map_err(Error::msg)
    }
}

// -- Flat aggregation circuit wrapper --------------------------------- //
//
// `NoirFlatAggregationCircuit` is intentionally NOT defined here. The
// flat tier circuits (`outbe-flat-aggregation-circuit-n*`) have a
// witness shape parameterised by `N` (N copies of `(pk, signature,
// nonce)` plus `2*N` public inputs), which is naturally expressed by
// a generic over `const N: u32` on the consumer side. The wallet
// integration in `outbe-integration::outbe-integrations-shared::witness`
// owns the witness builders and the noir_rs prove call site so the
// circuit core stays minimal -- this crate only owns the standalone
// ownership + full-proof wrappers above.

/// Derive the canonical UltraHonkKeccak verification key for a
/// compiled Noir circuit, via the noir_rs FFI.
///
/// **This is the function `xtask regenerate-canonical` calls** to mint
/// the `vk_bytes` field of every `outbe_zk_canonical::CircuitDescriptor`.
/// Must match the verifier path bit-for-bit: at runtime, the on-chain
/// `zk_verify` precompile passes the same canonical bytes to
/// `verify_ultra_honk_keccak`, and wallets generate proofs via
/// `prove_ultra_honk_keccak`. All three calls go through the same FFI
/// against the same `settings_ultra_honk_keccak`, so the artifacts
/// are guaranteed compatible.
///
/// Historical note: an earlier version of the xtask shelled out to
/// `bb write_vk --scheme ultra_honk --oracle_hash keccak` instead. That
/// produced different VK bytes than this FFI path, with the result that
/// no real (prover-generated) proof would verify against the committed
/// canonical VKs. The CLI / FFI difference is at the encoding layer
/// (different settings defaults — `optimized_solidity_verifier`,
/// `ipa_accumulation`, internal serialization). Going through the FFI
/// removes the divergence and keeps the design self-consistent.
pub fn derive_canonical_keccak_vk(bytecode: &str) -> anyhow::Result<Vec<u8>> {
    // Provision a generous fixed BN254 SRS that covers all canonical
    // tiers. `setup_srs_from_bytecode`'s subgroup-size heuristic
    // undercounts for the larger flat-aggregation circuits (N=8+),
    // causing barretenberg to abort with `prover trying to get too
    // many points in MemBn254CrsFactory`. 2^21 = 2,097,152 points
    // covers our largest circuit (N=64 acir ~5.5 MB) with headroom
    // and the SRS download is cached locally after the first run.
    //
    // `OUTBE_SRS_DAT` opts into a pre-downloaded `g1.dat` slice
    // (Aztec CRS raw layout): the canonical-regen network path
    // streams ~128 MiB from `crs.aztec.network` through
    // `reqwest::blocking`, which intermittently aborts with a
    // `Decode { source: TimedOut }` mid-body on slow or transcoded
    // links. Setting the env var to a curl-prefetched `g1.dat`
    // sidesteps the download entirely; the resulting SRS bytes
    // (and therefore the canonical VK) are identical because the
    // file is a prefix of the same universal SRS.
    use crate::barretenberg::srs::setup_srs;
    const SRS_POINTS: u32 = 1 << 21;
    let srs_path = std::env::var("OUTBE_SRS_DAT").ok();
    let _ = setup_srs(SRS_POINTS, srs_path.as_deref()).map_err(Error::msg)?;
    let vk =
        get_ultra_honk_keccak_verification_key(bytecode, false, false, None).map_err(Error::msg)?;
    Ok(vk)
}

pub mod circuit_loader {
    use super::*;

    use anyhow::anyhow;
    use std::path::Path;

    /// Load the compiled Noir circuit bytecode from a JSON file
    ///
    /// The bytecode is generated by running `nargo compile` in the circuits directory.
    /// The output is typically found at `circuits/target/<circuit_name>.json`.
    pub fn load_circuit<P: AsRef<Path>>(path: P) -> anyhow::Result<CircuitBytecode> {
        let content = std::fs::read_to_string(path.as_ref())?;

        load_circuit_from_str(&content)
    }

    /// Load circuit bytecode from a string (useful for embedded bytecode)
    pub fn load_circuit_from_str(content: &str) -> anyhow::Result<CircuitBytecode> {
        // Parse JSON and extract the bytecode field
        let json: serde_json::Value =
            serde_json::from_str(content).map_err(|e| anyhow!("Invalid JSON: {}", e))?;

        // The bytecode is in the "bytecode" field of the compiled JSON
        let bytecode = json
            .get("bytecode")
            .and_then(|v| v.as_str())
            .ok_or_else(|| anyhow!("Missing 'bytecode' field in circuit JSON"))?
            .trim()
            .to_string();

        let hash = json
            .get("hash")
            .and_then(|v| v.as_str())
            .ok_or_else(|| anyhow!("Missing 'hash' field in circuit JSON"))?
            .trim()
            .to_string();

        Ok(CircuitBytecode { bytecode, hash })
    }
}

