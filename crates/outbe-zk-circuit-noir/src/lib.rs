    /// Dumps witness data as a complete Noir `#[test]` function that calls `main()`.
    /// The output can be copy-pasted into `main.nr` to debug circuit failures via `nargo test`.
    fn dump_witness_for_noir_tests(witness: &FullProofWitness) {
        let nonce = FieldElement::from_be_bytes_reduce(&witness.private_inputs.ownership.nonce);
        let expected_ownership =
            FieldElement::from_be_bytes_reduce(&witness.public_inputs.ownership.ownership);
        let nft_hash =
            FieldElement::from_be_bytes_reduce(&witness.public_inputs.ownership.nft_hash);
        let expected_merkle_root =
            FieldElement::from_be_bytes_reduce(&witness.public_inputs.merkle_root);

        fn fmt_bytes(bytes: &[u8]) -> String {
            let items: Vec<String> = bytes.iter().map(|b| format!("{:03}", b)).collect();
            format!("[{}]", items.join(", "))
        }

        let mut sibling_strs: Vec<String> = witness
            .private_inputs
            .merkle_path
            .iter()
            .map(|item| {
                format!(
                    "0x{}",
                    FieldElement::from_be_bytes_reduce(&item.node_hash).to_hex()
                )
            })
            .collect();
        while sibling_strs.len() < SPARSE_MERKLE_PATH_DEPTH {
            sibling_strs.push("0".to_string());
        }

        let mut index_strs: Vec<String> = witness
            .private_inputs
            .merkle_path
            .iter()
            .map(|item| match item.index {
                MerklePathElementIndex::Right => "1".to_string(),
                MerklePathElementIndex::Left => "0".to_string(),
                MerklePathElementIndex::Skip => "0".to_string(),
            })
            .collect();
        while index_strs.len() < SPARSE_MERKLE_PATH_DEPTH {
            index_strs.push("0".to_string());
        }

        println!("// --- Generated Noir test (copy-paste into main.nr) ---");
        println!("#[test]");
        println!("fn test_main_integration() {{");
        println!("    let nonce: Field = 0x{};", nonce.to_hex());
        println!(
            "    let pk_x_bytes: [u8; 32] = {};",
            fmt_bytes(&witness.private_inputs.ownership.public_key_x)
        );
        println!(
            "    let pk_y_bytes: [u8; 32] = {};",
            fmt_bytes(&witness.private_inputs.ownership.public_key_y)
        );
        println!(
            "    let signature: [u8; 64] = {};",
            fmt_bytes(&witness.public_inputs.ownership.signature)
        );
        println!(
            "    let merkle_path_siblings: [Field; 8] = [{}];",
            sibling_strs.join(", ")
        );
        println!(
            "    let merkle_path_indices: [u8; 8] = [{}];",
            index_strs.join(", ")
        );
        println!(
            "    let expected_ownership: Field = 0x{};",
            expected_ownership.to_hex()
        );
        println!("    let nft_hash: Field = 0x{};", nft_hash.to_hex());
        println!(
            "    let expected_merkle_root: Field = 0x{};",
            expected_merkle_root.to_hex()
        );
        println!();
        println!("    main(nonce, pk_x_bytes, pk_y_bytes, signature, merkle_path_siblings, merkle_path_indices, expected_ownership, nft_hash, expected_merkle_root);");
        println!("}}");
        println!("// --- End generated Noir test ---");
    }

